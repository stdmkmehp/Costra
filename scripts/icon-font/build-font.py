#!/usr/bin/env fontforge
# -*- coding: utf-8 -*-
"""
Costra 图标字体 · 第 2 步（FontForge）：中心线 SVG → 描边扩展 → 去重叠 → TTF。

前置：先运行 `node build-svg.mjs` 产出 dist/glyph-svg/*.stroke.svg (+ .fill.svg) 与 dist/glyphs.json。

用 FontForge 的几何描边扩展 stroke()（工业级健壮，规避 paperjs-offset 死循环）：
  1. importOutlines(stroke svg) → 导入描边中心线为开放/闭合轮廓
  2. stroke("circular", 62.5, round, round) → 扩展为 1.5(em 缩放后)宽的填充轮廓
  3. importOutlines(fill svg) → 追加实心形状（圆点等，不参与描边扩展）
  4. removeOverlap + correctDirection + round → 合并重叠、修正朝向

产出：
  dist/iconfont.ttf
  miniprogram/styles/iconfont.wxss  （@font-face base64 + .costra-icon）
  dist/preview.html                 （三态预览，浏览器打开核验）

运行：fontforge -script build-font.py
"""
import os
import sys
import json
import base64

try:
    import fontforge
    import psMat
except ImportError:
    sys.stderr.write("必须用 FontForge 运行：fontforge -script build-font.py\n")
    sys.exit(1)

HERE = os.path.dirname(os.path.abspath(sys.argv[0]))
DIST = os.path.join(HERE, "dist")
GLYPH_SVG = os.path.join(DIST, "glyph-svg")
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MP_WXSS = os.path.join(ROOT, "miniprogram", "styles", "iconfont.wxss")

VB = 24
EM = 1000
ASCENT = 800
DESCENT = 200
STROKE = 1.5
STROKE_EM = STROKE * EM / VB  # 62.5
TARGET_EM = EM * 20.0 / 24.0  # 833：对齐 demo fit 的 20/24 光学尺寸

with open(os.path.join(DIST, "glyphs.json"), "r") as f:
    glyphs = json.load(f)

font = fontforge.font()
font.encoding = "UnicodeFull"
font.em = EM
font.ascent = ASCENT
font.descent = DESCENT
font.familyname = "costra-icons"
font.fontname = "costra-icons"
font.fullname = "costra-icons"
font.copyright = "Costra category icons"


def normalize_center(glyph):
    """等比缩放到统一尺寸并居中到 em 盒中线（消除 FontForge SVG 导入的缩放/定位差异）。"""
    bb = glyph.boundingBox()  # (xmin, ymin, xmax, ymax)
    gw = bb[2] - bb[0]
    gh = bb[3] - bb[1]
    if gw <= 0 or gh <= 0:
        return
    sc = TARGET_EM / max(gw, gh)
    glyph.transform(psMat.scale(sc))
    bb = glyph.boundingBox()
    cx = (bb[0] + bb[2]) / 2.0
    cy = (bb[1] + bb[3]) / 2.0
    # 水平居中到 EM/2；垂直居中到行盒中线 (ascent-descent)/2
    glyph.transform(psMat.translate(EM / 2.0 - cx, (ASCENT - DESCENT) / 2.0 - cy))


def import_scaled(glyph, svg_path):
    """导入 SVG 轮廓；若 FontForge 按 24 坐标系导入（未按 EM 缩放）则补一次缩放。"""
    glyph.importOutlines(svg_path)
    xmin, ymin, xmax, ymax = glyph.boundingBox()
    h = ymax - ymin
    # 期望字形高度在 EM 量级（~800）；若明显偏小说明按 viewBox(24) 导入 → 放大到 EM
    if h > 0 and h < 100:
        glyph.transform(psMat.scale(float(EM) / float(VB)))


for gi in glyphs:
    key = gi["key"]
    cp = gi["codepoint"]
    g = font.createChar(cp, key)

    # 1. 描边中心线
    stroke_svg = os.path.join(GLYPH_SVG, "%s-%s.stroke.svg" % (gi["cpHex"], key))
    import_scaled(g, stroke_svg)

    # 2. 几何描边扩展（圆帽/圆角）
    try:
        g.stroke("circular", STROKE_EM, "round", "round")
    except TypeError:
        # 兼容旧版 API（关键字参数）
        g.stroke("circular", STROKE_EM, cap="round", join="round")

    # 3. 追加实心形状（不参与描边扩展）
    if gi.get("hasFill"):
        fill_svg = os.path.join(GLYPH_SVG, "%s-%s.fill.svg" % (gi["cpHex"], key))
        import_scaled(g, fill_svg)

    # 4. 合并 + 朝向 + 归一化居中 + 取整
    g.removeOverlap()
    g.correctDirection()
    normalize_center(g)
    g.round()
    g.width = EM

    sys.stderr.write("glyph: U+%s %s\n" % (gi["cpHex"].upper(), key))

ttf_path = os.path.join(DIST, "iconfont.ttf")
font.generate(ttf_path)
sys.stderr.write("generated %s\n" % ttf_path)

# —— 内联 wxss（base64）——
with open(ttf_path, "rb") as f:
    b64 = base64.b64encode(f.read()).decode("ascii")

wxss = (
    "/* AUTO-GENERATED by scripts/icon-font/build-font.py — DO NOT EDIT. */\n"
    "@font-face {\n"
    '  font-family: "costra-icons";\n'
    '  src: url("data:font/ttf;base64,%s") format("truetype");\n'
    "}\n"
    ".costra-icon {\n"
    '  font-family: "costra-icons" !important;\n'
    "  font-style: normal;\n"
    "  font-weight: normal;\n"
    "  font-variant: normal;\n"
    "  text-transform: none;\n"
    "  line-height: 1;\n"
    "  -webkit-font-smoothing: antialiased;\n"
    "  -moz-osx-font-smoothing: grayscale;\n"
    "}\n"
) % b64
with open(MP_WXSS, "w") as f:
    f.write(wxss)
sys.stderr.write("wrote %s (%.1f KB base64)\n" % (MP_WXSS, len(b64) / 1024.0))

# —— 预览 html（三态）——
cells = []
for gi in glyphs:
    ch = "&#x%s;" % gi["cpHex"]
    cells.append(
        '<div class="cell"><div class="row">'
        '<span class="badge n">%s</span>'
        '<span class="badge ink">%s</span>'
        '<span class="badge green">%s</span>'
        "</div><div class=\"label\">%s · %s · U+%s</div></div>"
        % (ch, ch, ch, gi["label"], gi["key"], gi["cpHex"].upper())
    )

preview = (
    '<!DOCTYPE html><html lang="zh-CN"><head><meta charset="UTF-8"/>'
    "<title>Costra iconfont 预览</title><style>"
    "@font-face{font-family:'costra-icons';src:url(data:font/ttf;base64,%s) format('truetype');}"
    ":root{--bone:#f1f2ec;--ink:#1c1b1a;--green:#07c160;--bg:rgba(28,27,26,.06);--icon:rgba(28,27,26,.62);}"
    "body{margin:0;background:var(--bone);color:var(--ink);font-family:-apple-system,'PingFang SC',sans-serif;padding:32px 16px 64px;}"
    "h1{font-size:20px;text-align:center;margin:0 0 4px;}"
    ".sub{text-align:center;color:rgba(28,27,26,.45);font-size:12px;margin-bottom:28px;}"
    ".grid{max-width:560px;margin:0 auto;display:grid;grid-template-columns:1fr;row-gap:12px;}"
    ".row{display:flex;align-items:center;gap:14px;}"
    ".badge{width:48px;height:48px;border-radius:50%%;display:flex;align-items:center;justify-content:center;"
    "font-family:'costra-icons';font-size:28px;line-height:1;background:var(--bg);color:var(--icon);}"
    ".badge.ink{background:var(--ink);color:var(--bone);}"
    ".badge.green{background:var(--green);color:#fff;}"
    ".label{margin-top:4px;font-size:12px;color:rgba(28,27,26,.55);}"
    "</style></head><body>"
    "<h1>Costra iconfont · FontForge 产出预览</h1>"
    '<div class="sub">每行三态：默认 / 选中黑 / 选中绿 · 共 %d 字形</div>'
    '<div class="grid">%s</div></body></html>'
) % (b64, len(glyphs), "\n".join(cells))

with open(os.path.join(DIST, "preview.html"), "w") as f:
    f.write(preview)
sys.stderr.write("wrote dist/preview.html\n")

print("OK: %d glyphs -> dist/iconfont.ttf, miniprogram/styles/iconfont.wxss, dist/preview.html" % len(glyphs))
