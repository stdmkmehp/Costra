--============================================================================
-- Costra · Migration 0016 · entries_change_seq CACHE 1
--============================================================================
-- 根因修复：BUG-asset-stale-on-copy-entry
--
-- PG SEQUENCE 的CACHE 100 让不同连接预取独立号段，导致跨连接 nextval
-- 全局非单调。代码多处假设"seq 严格递增"（资产 baseline 谓词、sync watermark），
-- CACHE 100 下该假设不成立。
--
-- CACHE 1 后每次 nextval 实时从全局锁取号，恢复严格单调语义。
-- 本项目量级下性能影响可忽略。
--
-- 注意：ALTER SEQUENCE 立即生效，但已被各连接预取的旧号段不会回滚，
-- 需等旧连接用完各自号段或被idle 回收重建后才彻底消除乱序窗口。
-- 建议低峰期执行。
--============================================================================

ALTER SEQUENCE entries_change_seq CACHE 1;
